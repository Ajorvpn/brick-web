/* 5. Emblem contours → ExtrudeGeometry shapes                      */
/* ---------------------------------------------------------------- */

async function bakeEmblemContours() {
  const RES = 1024;
  const levels = [];

  for (const level of EMBLEM_LEVELS) {
    const mask = new Float32Array(RES * RES);
    rasterize(level.paths, RES, RES, { ox: 0, oy: 0, size: RES, mask });
    const loops = traceContours(mask, RES, RES, 0.5)
      .map((pts) => ({ pts, area: Math.abs(polygonArea(pts)) }))
      .filter((l) => l.area > RES * RES * 0.0004)
      .sort((a, b) => b.area - a.area)
      .map((l) => simplify(l.pts, 1.1))
      .filter((pts) => pts.length >= 3)
      .map((pts) =>
        pts.map(([x, y]) => [x / RES, y / RES]),
      );
    levels.push({ id: level.id, height: level.height, contours: loops });
    console.log(
      `  emblem/${level.id}: ${loops.length} contour(s), ${loops.reduce((n, c) => n + c.length, 0)} points`,
    );
  }

  const ts = `/*
 * GENERATED FILE — do not edit.
 * Produced by tools/bake-bricks/bake.mjs from the original artwork in
 * tools/bake-bricks/stamps.mjs. Coordinates are normalised (0..1, y down);
 * the scene maps them onto the keystone face and extrudes them.
 */

/** One closed loop, normalised to the emblem's unit box, y down. */
export type EmblemContour = [number, number][];

export interface EmblemLevel {
  id: string;
  /** relief height, relative to the emblem's own maximum */
  height: number;
  contours: EmblemContour[];
}

export const EMBLEM_LEVELS: EmblemLevel[] = ${JSON.stringify(levels, null, 0)
    .replace(/"id":/g, "id:")
    .replace(/"height":/g, "height:")
    .replace(/"contours":/g, "contours:")};
`;

  await fs.writeFile(path.join(SRC, "emblem_contours.generated.ts"), ts, "utf8");
}

