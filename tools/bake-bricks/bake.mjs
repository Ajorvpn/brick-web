/**
 * Two small sheets for the stage cards, so the CSS brick in §04 is the same
 * fired clay as the wall instead of a gradient that only pretends to be.
 * "lit" is the in-progress state: the same brick, warmed from the inside.
 */
async function bakeStageSprites() {
  const w = 512;
  const h = 128;
  const base = saturate(hex("#A87750"), 0.94);
  const { height, grain, patch, chips } = clayRelief(0x7a31, w, h);

  const shade = heightToShade(height, w, h, 0.3);
  const solid = new Uint8Array(w * h * 3);
  const lit = new Uint8Array(w * h * 3);
  const ember = hex("#E2552F");

  for (let y = 0; y < h; y++) {
    for (let x = 0; x < w; x++) {
      const i = (y * w + x) * 3;
      const u = x / w;
      const v = y / h;
      const edge = Math.min(u, 1 - u, v, 1 - v);
      const wear = smoothstep(0.0, 0.05, edge);
      let c = mix3(
        scale3(base, 0.9),
        scale3(base, 1.07),
        clamp01(0.4 + (patch[y * w + x] - 0.5) * 1.2),
      );
      c = scale3(c, 0.95 + (grain[y * w + x] - 0.5) * 0.16);
      c = scale3(c, 1 - shade[y * w + x] * 0.35);
      c = scale3(c, 0.86 + wear * 0.14);
      c = mix3(c, scale3(c, 0.55), chips[y * w + x] * 0.8);
      solid[i] = Math.round(c[0] * 255);
      solid[i + 1] = Math.round(c[1] * 255);
      solid[i + 2] = Math.round(c[2] * 255);

      const glow = smoothstep(0.55, 0.0, Math.hypot(u - 0.5, (v - 0.5) * 1.6));
      const warmth = mix3(c, ember, 0.18 + glow * 0.22);
      lit[i] = Math.round(Math.min(1, warmth[0] * (1 + glow * 0.16)) * 255);
      lit[i + 1] = Math.round(Math.min(1, warmth[1] * (1 + glow * 0.06)) * 255);
      lit[i + 2] = Math.round(Math.min(1, warmth[2]) * 255);
    }
  }

  await writeMap("stage-solid.webp", solid, w, h, { quality: 88 });
  await writeMap("stage-lit.webp", lit, w, h, { quality: 88 });
}

/* ---------------------------------------------------------------- */
/* 4. Keystone: the highest-detail object on the page               */
/* ---------------------------------------------------------------- */

const KEY_W = 2048;
const KEY_H = 512;
const EMBLEM_SIZE = 0.46; // world units of the 2.2-unit face
const FACE_UNITS = 2.2;

async function bakeKeystone() {
  const w = KEY_W;
  const h = KEY_H;
  const pxPerUnit = w / FACE_UNITS;
  const emblemPx = EMBLEM_SIZE * pxPerUnit;
  const cx = w / 2;
  const cy = h / 2;

  const grain = generate(w, h, (x, y) =>
    fbm(x * 0.055, y * 0.055, 0x4d2, 1e6, 1e6, 4, 0.55),
  );
  const patch = generate(w, h, (x, y) =>
    fbm(x * 0.007, y * 0.007, 0x1c7, 1e6, 1e6, 4, 0.6),
  );

  // the carved frame groove around the emblem bed
  const grooveOuter = emblemPx * 0.5 + 26;
  const grooveInner = emblemPx * 0.5 + 6;
  const groove = generate(w, h, (x, y) => {
    const d = Math.hypot(x - cx, (y - cy) * 1.0);
    const inRing = smoothstep(grooveOuter + 1.5, grooveOuter - 1.5, d) *
      smoothstep(grooveInner - 1.5, grooveInner + 1.5, d);
    return inRing;
  });

  const height = new Float32Array(w * h);
  for (let y = 0; y < h; y++) {
    for (let x = 0; x < w; x++) {
      const i = y * w + x;
      const u = x / w;
      const v = y / h;
      const edge = Math.min(u, 1 - u, v, 1 - v);
      const d = Math.hypot(x - cx, y - cy);
      // the emblem bed is pressed very slightly proud of the face
      const bed = smoothstep(emblemPx * 0.54, emblemPx * 0.46, d) * 0.05;
      height[i] =
        0.56 +
        (grain[i] - 0.5) * 0.07 +
        (patch[i] - 0.5) * 0.028 +
        0.07 * smoothstep(0.0, 0.035, edge) -
        groove[i] * 0.34 +
        bed;
    }
  }

  const nrm = heightToNormal(height, w, h, 1.5);
  const aoMap = heightToAO(height, w, h, 10, 2.6);
  const shade = heightToShade(height, w, h, 0.22);

  const sand = hex("#C8A06E");
  const rose = hex("#A9583B");
  const soot = hex("#3a2419");
  const goldBed = hex("#8C6A3A");

  const albedo = new Uint8Array(w * h * 3);
  const rough = new Uint8Array(w * h * 3);

  for (let y = 0; y < h; y++) {
    for (let x = 0; x < w; x++) {
      const i = y * w + x;
      const u = x / w;
      const v = y / h;
      const edge = Math.min(u, 1 - u, v, 1 - v);
      const d = Math.hypot(x - cx, y - cy);

      let c = mix3(rose, sand, clamp01(0.2 + patch[i] * 1.2));
      c = scale3(c, 0.9 + (grain[i] - 0.5) * 0.2);
      // edge wear: pale, abraded clay along the arrises
      const wear = 1 - smoothstep(0.0, 0.035, edge);
      c = mix3(c, MORTAR_LIGHT, wear * 0.55);
      // soot and handling grime in the groove and around the bed
      c = mix3(c, soot, groove[i] * 0.5);
      // the inlay bed: a warmer, dustier clay, slightly darkened
      const bed = smoothstep(emblemPx * 0.56, emblemPx * 0.5, d);
      c = mix3(c, goldBed, bed * 0.22);
      c = scale3(c, clamp01(shade[i]) * (0.62 + 0.38 * (aoMap[i * 3] / 255)));

      const o = i * 3;
      const rgb = to8(c);
      albedo[o] = rgb[0];
      albedo[o + 1] = rgb[1];
      albedo[o + 2] = rgb[2];

      const r = clamp01(0.86 + groove[i] * 0.1 + (1 - grain[i]) * 0.06);
      const g = Math.round(r * 255);
      rough[o] = g;
      rough[o + 1] = g;
      rough[o + 2] = g;
    }
  }

  await writeMap("keystone-albedo.webp", albedo, w, h, { quality: 93 });
  await writeMap("keystone-normal.webp", nrm, w, h, { nearLossless: true });
  await writeMap("keystone-roughness.webp", rough, w, h, { nearLossless: true });

  // AO for the keystone is read from the same silhouette; ship a compact one
  await writeMap("keystone-ao.webp", aoMap, w, h, { nearLossless: true });
}

