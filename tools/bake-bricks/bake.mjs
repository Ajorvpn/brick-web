#!/usr/bin/env node
/**
 * bake.mjs — the committed, reproducible bake for "The Stamped Wall".
 *
 *   node tools/bake-bricks/bake.mjs
 *
 * Emits, into apps/web/public/bricks/:
 *   clay-albedo.webp    6 tone cells (512x128 each) stacked in one atlas
 *   clay-normal.webp    8 face cells: 4 plain tones + shamseh/rosette/wedge/lionsun
 *   clay-roughness.webp 8 face cells, aligned with the normal atlas
 *   clay-ao.webp        8 face cells, aligned with the normal atlas
 *   glaze-albedo/normal/roughness.webp   turquoise glaze + crazing
 *   keystone-albedo/normal/roughness.webp  the hero brick, 4x the face budget
 *   apps/web/src/components/three/emblem_contours.generated.ts
 *
 * Texture sourcing / licensing: every pixel here is generated by this script
 * from procedural noise and the original stamp polygons in stamps.mjs. No
 * third-party texture, photograph or SVG is downloaded, resampled or traced,
 * so there is no CC0 attribution to carry and no licence that could be wrong.
 * The reference photographs listed in stamps.mjs were studied for proportion
 * and palette only.
 *
 * Encoding: WebP. Albedo at q=90 (photographic), normal/roughness/AO at
 * near-lossless (lossy WebP smears the fine gradient of a normal map into
 * blotches). Budget is checked and printed at the end: the whole scene set
 * stays under 6 MB transferred.
 */

