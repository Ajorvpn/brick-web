const written = [];

async function writeMap(relPath, data, w, h, { nearLossless = false, quality = 90 } = {}) {
  const abs = path.join(OUT, relPath);
  await fs.mkdir(path.dirname(abs), { recursive: true });
  const channels = data.length / (w * h);
  let pipe = sharp(Buffer.from(data.buffer ?? data, data.byteOffset ?? 0, data.byteLength), {
    raw: { width: w, height: h, channels },
  });
  pipe = pipe.webp(
    nearLossless ? { nearLossless: true, quality: 70, effort: 6 } : { quality, effort: 6 },
  );
  await pipe.toFile(abs);
  const stat = await fs.stat(abs);
  written.push({ file: relPath, bytes: stat.size, w, h });
  return abs;
}

/* ---------------------------------------------------------------- */
/* 1. Clay tone atlas                                               */
/* ---------------------------------------------------------------- */

async function bakeClayAlbedo() {
  const atlasH = CELL_H * TONES.length;
  const out = new Uint8Array(CELL_W * atlasH * 3);

  for (let t = 0; t < TONES.length; t++) {
    const tone = TONES[t];
    const { height, grain, patch, chips } = clayRelief(tone.seed);
    const base = saturate(hex(tone.base), tone.sat);
    const shade = heightToShade(height, CELL_W, CELL_H, 0.26);
    const rand = rng(tone.seed ^ 0x1234);

    for (let y = 0; y < CELL_H; y++) {
      for (let x = 0; x < CELL_W; x++) {
        const i = y * CELL_W + x;
        const v = y / CELL_H;

        // firing variation: warmer and lighter in patches, cooler in others
        let c = mix3(
          scale3(base, 0.9),
          scale3(base, 1.07),
          clamp01(0.4 + (patch[i] - 0.5) * 1.15),
        );
        // sand grain modulates value, not hue
        c = scale3(c, 0.95 + (grain[i] - 0.5) * 0.15);

        // soot: strongest at the bottom of the face, where water runs
        const soot = tone.soot * smoothstep(0.15, 1.0, v) * (0.55 + patch[i] * 0.7);
        c = mix3(c, hex("#1a1210"), clamp01(soot * 0.55));

        // a chipped corner exposes pale, unburnt clay
        if (chips[i] > 0) c = mix3(c, MORTAR_LIGHT, clamp01(chips[i] * 0.55));

        // directional shade baked from the relief (light from upper-left)
        const lit = shade[i];
        c = scale3(c, clamp01(lit));

        const o = ((t * CELL_H + y) * CELL_W + x) * 3;
        const rgb = to8(c);
        out[o] = rgb[0];
        out[o + 1] = rgb[1];
        out[o + 2] = rgb[2];
      }
    }
    // fine dust settled in the low spots: a whisper, not a wash
    void rand;
  }

  await writeMap("clay-albedo.webp", out, CELL_W, atlasH, { quality: 92 });
}

/* ---------------------------------------------------------------- */
/* 2. Per-face normal / roughness / AO atlases                      */
/* ---------------------------------------------------------------- */

async function bakeFaceAtlases() {
  const rows = FACE_CELLS.length;
  const atlasH = CELL_H * rows;
  const normal = new Uint8Array(CELL_W * atlasH * 3);
  const rough = new Uint8Array(CELL_W * atlasH * 3);
  const ao = new Uint8Array(CELL_W * atlasH * 3);

  FACE_CELLS.forEach((id, row) => {
    const toneSeed = TONES[row < 4 ? row : (row + 1) % TONES.length].seed;
    const relief = clayRelief(toneSeed);
    const height = Float32Array.from(relief.height);

    const stampId = id.startsWith("plain") ? "plain" : id;
    if (stampId !== "plain") {
      const stamp = stampRelief(CELL_W, CELL_H, stampId, toneSeed);
      // pressed IN, with a hair of build-up at the shoulder
      for (let i = 0; i < height.length; i++) {
        height[i] -= stamp[i] * 0.34;
        height[i] += Math.max(0, stamp[i] - 0.85) * 0.5;
      }
    }
    if (id === "plain-d") {
      // the smoked cell carries one hairline crack across the face
      const crackMask = stampRelief(CELL_W, CELL_H, "crack-a", toneSeed);
      for (let i = 0; i < height.length; i++) height[i] -= crackMask[i] * 0.22;
    }

    const nrm = heightToNormal(height, CELL_W, CELL_H, 2.6);
    const aoMap = heightToAO(height, CELL_W, CELL_H, 7, 2.4);
    const low = blur(height, CELL_W, CELL_H, 5);

    for (let y = 0; y < CELL_H; y++) {
      for (let x = 0; x < CELL_W; x++) {
        const i = y * CELL_W + x;
        const o = ((row * CELL_H + y) * CELL_W + x) * 3;
        normal[o] = nrm[i * 3];
        normal[o + 1] = nrm[i * 3 + 1];
        normal[o + 2] = nrm[i * 3 + 2];

        ao[o] = aoMap[i * 3];
        ao[o + 1] = aoMap[i * 3 + 1];
        ao[o + 2] = aoMap[i * 3 + 2];

        // matte fired clay, a little smoother where the face was polished
        // by the mould; debossed stamps hold chalky dust → slightly rougher
        const r = clamp01(0.9 + (0.5 - low[i]) * 0.18);
        const g = Math.round(r * 255);
        rough[o] = g;
        rough[o + 1] = g;
        rough[o + 2] = g;
      }
    }
  });

  await writeMap("clay-normal.webp", normal, CELL_W, atlasH, { nearLossless: true });
  await writeMap("clay-roughness.webp", rough, CELL_W, atlasH, { nearLossless: true });
  await writeMap("clay-ao.webp", ao, CELL_W, atlasH, { nearLossless: true });
}

/* ---------------------------------------------------------------- */
/* 3. Glaze                                                         */
/* ---------------------------------------------------------------- */

async function bakeGlaze() {
  const w = CELL_W;
  const h = CELL_H;
  const base = hex("#22807E");
  const deep = hex("#146A6E");
  const clay = hex("#B87A4B");

  const drift = generate(w, h, (x, y) =>
    fbm(x * 0.01, y * 0.03, 0x9a1, 1e6, 1e6, 4, 0.55),
  );
  // crazing: the fine crackle of an old alkali glaze
  const crack = generate(w, h, (x, y) => {
    const a = voronoi(x * 0.09, y * 0.09, 0x77c, 22);
    const b = voronoi(x * 0.22, y * 0.22, 0x3e5, 54);
    const edgeA = smoothstep(0.0, 0.16, a.f2 - a.f1);
    const edgeB = smoothstep(0.0, 0.13, b.f2 - b.f1);
    return Math.min(edgeA, edgeB);
  });

  const albedo = new Uint8Array(w * h * 3);
  const normal = new Uint8Array(w * h * 3);
  const rough = new Uint8Array(w * h * 3);

  // relief: crackle valleys + a gentle pool of thickness across the face
  const height = new Float32Array(w * h);
  for (let y = 0; y < h; y++) {
    for (let x = 0; x < w; x++) {
      const i = y * w + x;
      const u = x / w;
      const v = y / h;
      const edge = Math.min(u, 1 - u, v, 1 - v);
      height[i] = 0.6 + crack[i] * 0.16 + 0.1 * smoothstep(0.0, 0.08, edge);
    }
  }
  const nrm = heightToNormal(height, w, h, 2.4);
  const aoMap = heightToAO(height, w, h, 4, 1.4);

  for (let y = 0; y < h; y++) {
    for (let x = 0; x < w; x++) {
      const i = y * w + x;
      const u = x / w;
      const v = y / h;
      const edge = Math.min(u, 1 - u, v, 1 - v);

      let c = mix3(deep, base, clamp01(0.25 + drift[i] * 1.1));
      // the glaze runs thin at the arrises and the clay shows through
      const thin = 1 - smoothstep(0.0, 0.075, edge);
      c = mix3(c, clay, thin * 0.85);
      // crackle lines: dirt settles in, so they read slightly darker
      c = mix3(c, scale3(c, 0.6), (1 - crack[i]) * 0.75);
      const ao = aoMap[i * 3] / 255;
      c = scale3(c, 0.75 + ao * 0.35);

      const o = i * 3;
      const rgb = to8(c);
      albedo[o] = rgb[0];
      albedo[o + 1] = rgb[1];
      albedo[o + 2] = rgb[2];

      normal[o] = nrm[i * 3];
      normal[o + 1] = nrm[i * 3 + 1];
      normal[o + 2] = nrm[i * 3 + 2];

      // glaze body is glassy; the crackle and the thin arrises are duller
      const r = clamp01(0.16 + (1 - crack[i]) * 0.4 + thin * 0.55);
      const g = Math.round(r * 255);
      rough[o] = g;
      rough[o + 1] = g;
      rough[o + 2] = g;
    }
  }

  await writeMap("glaze-albedo.webp", albedo, w, h, { quality: 92 });
  await writeMap("glaze-normal.webp", normal, w, h, { nearLossless: true });
  await writeMap("glaze-roughness.webp", rough, w, h, { nearLossless: true });
}

