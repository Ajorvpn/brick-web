/**
 * clayRelief — the micro-surface of one pressed clay face.
 *
 * Deliberately anisotropic: extrusion striations are long and horizontal,
 * the sand grain is isotropic and fine, and the very low frequencies are
 * firing patches. The sampler clamps at the borders (a brick face ends, it
 * does not tile), so nothing here needs to wrap.
 */
function clayRelief(seed, w = CELL_W, h = CELL_H) {
  const rand = rng(seed);
  const grain = generate(w, h, (x, y) =>
    fbm(x * 0.14, y * 0.14, seed + 11, 1e6, 1e6, 3, 0.55),
  );
  const striation = generate(w, h, (x, y) =>
    fbm(x * 0.012, y * 0.55, seed + 23, 1e6, 1e6, 2, 0.5),
  );
  const patch = generate(w, h, (x, y) =>
    fbm(x * 0.008, y * 0.03, seed + 37, 1e6, 1e6, 4, 0.55),
  );

  // pores: small round craters, denser toward the arrises
  const pores = generate(w, h, () => 0);
  const poreCount = Math.round((w * h) / 1500);
  for (let i = 0; i < poreCount; i++) {
    const cx = rand() * w;
    const cy = rand() * h;
    const r = 0.7 + rand() * 2.4;
    const depth = 0.35 + rand() * 0.65;
    for (let y = Math.floor(cy - r); y <= cy + r; y++) {
      for (let x = Math.floor(cx - r); x <= cx + r; x++) {
        if (x < 0 || y < 0 || x >= w || y >= h) continue;
        const d = Math.hypot(x - cx, y - cy) / r;
        if (d > 1) continue;
        const v = (1 - d) * (1 - d) * depth;
        const i2 = y * w + x;
        if (v > pores[i2]) pores[i2] = v;
      }
    }
  }

  // chipped corners / arrises — a few per tone, never all four
  const chips = generate(w, h, () => 0);
  const chipCount = 2 + Math.floor(rand() * 3);
  for (let c = 0; c < chipCount; c++) {
    const corner = Math.floor(rand() * 4);
    const cxp = corner % 2 === 0 ? -4 : w + 4;
    const cyp = corner < 2 ? -3 : h + 3;
    const r = 8 + rand() * 22;
    const wobble = 0.7 + rand() * 0.9;
    for (let y = Math.floor(cyp - r); y <= cyp + r; y++) {
      for (let x = Math.floor(cxp - r); x <= cxp + r; x++) {
        if (x < 0 || y < 0 || x >= w || y >= h) continue;
        const d = Math.hypot(x - cxp, y - cyp) / r;
        if (d > 1) continue;
        const ang = Math.atan2(y - cyp, x - cxp);
        const edge = 1 + Math.sin(ang * 5 * wobble) * 0.08;
        const v = clamp01((edge - d) * 3);
        const i2 = y * w + x;
        if (v > chips[i2]) chips[i2] = v;
      }
    }
  }

  const height = new Float32Array(w * h);
  for (let y = 0; y < h; y++) {
    for (let x = 0; x < w; x++) {
      const i = y * w + x;
      const u = x / w;
      const v = y / h;
      // soft recess of the arris so the bevel catches light like worn clay
      const edge = Math.min(u, 1 - u, v, 1 - v);
      const arris = smoothstep(0.0, 0.05, edge);
      height[i] =
        0.55 +
        (grain[i] - 0.5) * 0.16 +
        (striation[i] - 0.5) * 0.09 +
        (patch[i] - 0.5) * 0.07 +
        0.06 * arris -
        pores[i] * 0.3 -
        chips[i] * 0.75;
    }
  }

  return { height, grain, striation, patch, pores, chips, rand };
}

/** A stamp pressed into the face: negative relief under a soft bevel. */
function stampRelief(cellW, cellH, id, seed) {
  const def = STAMP_DEFS.find((d) => d.id === id);
  const mask = new Float32Array(cellW * cellH);
  if (!def || def.paths.length === 0) return mask;
  const size = Math.min(cellW, cellH) * 0.82;
  rasterize(def.paths, cellW, cellH, {
    ox: (cellW - size) / 2,
    oy: (cellH - size) / 2,
    size,
    mask,
  });
  // press: soften the rim so the stamp has a shoulder, not a cliff
  const soft = blur(mask, cellW, cellH, Math.max(1, size * 0.012));
  const out = new Float32Array(cellW * cellH);
  for (let i = 0; i < out.length; i++) out[i] = Math.min(1, soft[i] * 1.06);
  return out;
}

